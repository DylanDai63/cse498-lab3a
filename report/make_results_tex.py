#!/usr/bin/env python3
"""Write report/results.tex from the acceptance JSON files in report/results/.

Every acceptance number in the report comes from here; re-run after a new run:

    python report/make_results_tex.py

Inputs: the JSON files written by `scripts/acceptance_run.sh --json PATH`, one per run,
listed in RUNS in the order they were run. The notes column records what the console
and ROS logs showed for that run (details in the course folder's run_log.md).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
W1, W2 = "\\texttt{warehouse\\_models}", "\\texttt{warehouse\\_models\\_person}"
# (file, world, detector commit, threads, note)
RUNS = [
    ("acceptance_run1_warehouse_models_person.json", W2, "7241462", "default", ""),
    ("acceptance_run2_warehouse_models.json", W1, "6e7f4db", "default", ""),
    ("acceptance_run3_warehouse_models_person.json", W2, "ddf8335", "4", ""),
]


def tex(s: str) -> str:
    return s.replace("_", "\\_")


def num(x, fmt="{:.2f}"):
    return "--" if x is None else fmt.format(x)


lines = ["% Generated by report/make_results_tex.py -- do not edit by hand."]
rows = []
lm_errs, dists, reached, navigable, total = [], [], 0, 0, 0
for k, (fname, world, commit, threads, note) in enumerate(RUNS, start=1):
    d = json.loads((RES / fname).read_text(encoding="utf-8"))
    cmds = d["commands"]
    r = sum(1 for c in cmds if c["outcome"] == "REACHED")
    rows.append(f"\\multicolumn{{6}}{{l}}{{\\textbf{{Run {k}}}: {world}, detector \\texttt{{{commit}}}, "
                f"threads {threads}; {r}/{len(cmds)} reached}} \\\\")
    if note:
        rows.append(f"\\multicolumn{{6}}{{l}}{{\\quad\\footnotesize\\textit{{{note}}}}} \\\\")
    for c in cmds:
        outcome = {"SKIPPED": "skipped$^{*}$", "REACHED": "reached"}.get(c["outcome"], c["outcome"].lower())
        rows.append(" & ".join([
            f"\\quad\\texttt{{{tex(c['command'])}}}",
            f"\\texttt{{{tex(c['landmark_id'])}}}",
            num(c["landmark_error_m"]),
            num(c["final_distance_m"]),
            num(c["elapsed_s"], "{:.1f}") if c["outcome"] != "SKIPPED" else "--",
            outcome,
        ]) + " \\\\")
        total += 1
        if c["landmark_error_m"] is not None:
            lm_errs.append(c["landmark_error_m"])
        if c["outcome"] != "SKIPPED" and c["landmark_error_m"] is not None:
            navigable += 1
        if c["outcome"] == "REACHED":
            reached += 1
            dists.append(c["final_distance_m"])
    rows.append("\\midrule")
rows.pop()

lines.append("\\newcommand{\\AcceptanceRows}{%")
lines.extend(rows)
lines.append("}")
lines.append(f"\\newcommand{{\\NRuns}}{{{len(RUNS)}}}")
lines.append(f"\\newcommand{{\\NCmds}}{{{total}}}")
lines.append(f"\\newcommand{{\\NNavigable}}{{{navigable}}}")
lines.append(f"\\newcommand{{\\NReached}}{{{reached}}}")
lines.append(f"\\newcommand{{\\NLandmarks}}{{{len(lm_errs)}}}")
lines.append(f"\\newcommand{{\\LmErrMin}}{{{num(min(lm_errs))}}}")
lines.append(f"\\newcommand{{\\LmErrMax}}{{{num(max(lm_errs))}}}")
lines.append(f"\\newcommand{{\\DistMin}}{{{num(min(dists))}}}")
lines.append(f"\\newcommand{{\\DistMax}}{{{num(max(dists))}}}")

(HERE / "results.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", HERE / "results.tex", f"runs={len(RUNS)} cmds={total} navigable={navigable} reached={reached} "
      f"lm_err=[{min(lm_errs):.2f},{max(lm_errs):.2f}] dist=[{min(dists):.2f},{max(dists):.2f}]")
